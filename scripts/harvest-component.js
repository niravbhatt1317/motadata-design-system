#!/usr/bin/env node
/**
 * harvest-component.js — Coverage Ledger harvester (step 1 of the conversion runbook).
 *
 * Given a component id, scans ALL 6 sources and emits a ledger skeleton so no source is missed:
 *   1. Storybook story exports        design-system/storybook/**\/<id>*.stories.js  (export const …)
 *   2. Doc pages                      design-system/storybook/**\/<id>*.mdx
 *   3. Every CSS class in EVERY LESS  src/design/*.less   (selectors mentioning the id / its family)
 *   4. Registry contract              design-system/components/registry/<id>.json
 *   5. Real component source(s)       src/components/**    (files/refs matching the id or M<Id>)
 *   6. (manual) sub-components it composes — flagged for the author to chase
 *
 * Usage:
 *   node design-system/scripts/harvest-component.js <id> [--extra <regex>] [--write]
 *     <id>        registry id, e.g. tag, button, checkbox, switch, input
 *     --extra     extra class-name regex fragment (e.g. "main-tags|loose-tags") for spread-out families
 *     --write     write to design-system/strategy/coverage/<id>.md (else prints to stdout)
 *
 * Output is a STARTING POINT — the author/agent still verifies Look·Feel·Behaviour against the
 * rendered Storybook and resolves every row. It guarantees the *enumeration* is complete.
 */
'use strict'
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..', '..') // UI/
const DS = path.join(ROOT, 'design-system')

const args = process.argv.slice(2)
const id = args.find((a) => !a.startsWith('--'))
if (!id) {
  console.error('usage: node harvest-component.js <id> [--extra <regex>] [--write]')
  process.exit(1)
}
const extra = args.includes('--extra') ? args[args.indexOf('--extra') + 1] : ''
const doWrite = args.includes('--write')

const exists = (p) => fs.existsSync(p)
const read = (p) => (exists(p) ? fs.readFileSync(p, 'utf8') : '')
function walk(dir, filterRe) {
  const out = []
  if (!exists(dir)) return out
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name)
    const st = fs.statSync(full)
    if (st.isDirectory()) out.push(...walk(full, filterRe))
    else if (filterRe.test(name)) out.push(full)
  }
  return out
}
const rel = (p) => path.relative(ROOT, p)

// ---- 1+2. stories + mdx ----
const sbDir = path.join(DS, 'storybook')
const storyFiles = walk(sbDir, new RegExp(`(^|/|\\b)${id}\\b.*\\.stories\\.js$`)).filter((f) =>
  path.basename(f).startsWith(id + '.')
)
const stories = []
for (const f of storyFiles) {
  for (const m of read(f).matchAll(/export const (\w+)/g)) stories.push(m[1])
}
const mdxFiles = walk(sbDir, new RegExp(`^${id}\\..*\\.mdx$`)).map(rel)

// ---- 3. every CSS class across all LESS ----
const lessDir = path.join(ROOT, 'src', 'design')
const lessFiles = walk(lessDir, /\.less$/)
// collect EVERY class selector, then keep those whose name belongs to the family (incl. names that
// START with the id, e.g. tag-green — a leading-char requirement would have missed those).
const stem = id.replace(/s$/, '')
const extraRe = extra ? new RegExp(extra) : null
const classRe = /\.([a-zA-Z][\w-]*)/g
const antRe = /\.@\{ant-prefix\}-([\w-]+)/g // LESS interpolation, e.g. .@{ant-prefix}-switch-inner
const classes = {} // class -> [files]
const keep = (cls, name, file) => {
  // family filter (not the prefix) decides relevance — catches .ant-switch / .ant-checkbox-inner too
  if (!(name.includes(id) || name.includes(stem) || (extraRe && extraRe.test(name)))) return
  ;(classes[cls] = classes[cls] || new Set()).add(path.basename(file))
}
for (const f of lessFiles) {
  const txt = read(f)
  for (const m of txt.matchAll(classRe)) keep(m[1], m[1], f)
  for (const m of txt.matchAll(antRe)) keep('ant-' + m[1], m[1], f)
}

// ---- 4. registry ----
const regPath = path.join(DS, 'components', 'registry', `${id}.json`)
let reg = null
try { reg = JSON.parse(read(regPath)) } catch (e) { /* none */ }
const regList = (k) => {
  const v = reg && reg[k]
  if (!v) return []
  if (Array.isArray(v)) return v.map((x) => (typeof x === 'string' ? x : x.name || JSON.stringify(x)))
  if (typeof v === 'object') return Object.keys(v)
  return [String(v)]
}

// ---- 5. component source files ----
const compDir = path.join(ROOT, 'src', 'components')
const Id = id.charAt(0).toUpperCase() + id.slice(1)
const srcRe = new RegExp(`(_base-[\\w-]*${id}|${id}[\\w-]*\\.vue|M${Id})`, 'i')
const srcFiles = walk(compDir, /\.vue$/).filter((f) => srcRe.test(read(f)) || srcRe.test(path.basename(f))).map(rel).slice(0, 12)

// ---- emit skeleton ----
const L = []
L.push(`# Coverage Ledger — \`${id}\`  (GENERATED SKELETON — verify & resolve every row)`)
L.push('')
L.push('> Generated by `harvest-component.js`. Enumeration is complete by construction; you still verify')
L.push('> Look (`getComputedStyle`) · Feel (real Playwright events) · Behaviour against the rendered Storybook,')
L.push('> and resolve every row to `✅` / `⛔ owner-excluded`. Zero `🔲` = done. Never self-exclude — escalate.')
L.push('')
L.push('## 0. Harvest (raw)')
L.push('')
L.push(`- **Story exports** (${storyFiles.length} file/s): ${stories.length ? stories.join(', ') : '— none found —'}`)
L.push(`- **Doc pages**: ${mdxFiles.length ? mdxFiles.join(', ') : '—'}`)
L.push(`- **CSS classes across all \`src/design/*.less\`** (${Object.keys(classes).length}): ${Object.keys(classes).length ? '' : '— none matched; try --extra —'}`)
for (const c of Object.keys(classes).sort()) L.push(`  - \`.${c}\` — ${[...classes[c]].join(', ')}`)
L.push(`- **Registry** (\`${exists(regPath) ? rel(regPath) : 'MISSING'}\`):`)
if (reg) {
  L.push(`  - props: ${regList('props').join(', ') || '—'}`)
  L.push(`  - variants: ${regList('variants').join(', ') || '—'}`)
  L.push(`  - states: ${regList('states').join(', ') || '—'}`)
  L.push(`  - events: ${regList('events').join(', ') || '—'}`)
  L.push(`  - slots: ${regList('slots').join(', ') || '—'}`)
  L.push(`  - a11y issues: ${(reg.a11y && (reg.a11y.issues || []).join('; ')) || '—'}`)
}
L.push(`- **Component source(s)**: ${srcFiles.length ? srcFiles.join(', ') : '— search src/components manually —'}`)
L.push('- **Sub-components it composes**: _(chase manually — e.g. status-tag, selected-pills; behaviours live here)_')
L.push('')

L.push('## 1. Rows to resolve (every variant · state · behaviour · prop)')
L.push('')
L.push('| Kind | Item | Source | Look ✓ | Feel ✓ | Behaviour ✓ | Status |')
L.push('| --- | --- | --- | --- | --- | --- | --- |')
for (const c of Object.keys(classes).sort()) L.push(`| variant/class | \`.${c}\` | LESS | | | | 🔲 |`)
for (const v of regList('variants')) L.push(`| variant | ${v} | registry | | | | 🔲 |`)
for (const s of regList('states')) L.push(`| state | ${s} | registry | | | | 🔲 |`)
for (const e of regList('events')) L.push(`| behaviour | emits \`${e}\` | registry | — | — | | 🔲 |`)
for (const p of regList('props')) L.push(`| prop | ${p} | registry | — | — | | 🔲 |`)
for (const sl of regList('slots')) L.push(`| slot | ${sl} | registry | | | | 🔲 |`)
for (const st of stories) L.push(`| story | ${st} (all its examples covered?) | storybook | | | | 🔲 |`)
L.push('')
L.push('## 2. Look diffs (fill from `verify-component.js`)')
L.push('')
L.push('| Element/state | Property | Storybook | Mine | Match |')
L.push('| --- | --- | --- | --- | --- |')
L.push('| | | | | |')
L.push('')
L.push('## 3. Proposed exclusions — OWNER decides (never self-exclude)')
L.push('')
L.push('| Item | Why proposed out | Owner decision |')
L.push('| --- | --- | --- |')
L.push('| | | |')
L.push('')
L.push('## 4. Gate')
L.push('')
L.push('- [ ] Harvest reviewed (all sources non-empty / explained)')
L.push('- [ ] Every row resolved (`✅` or `⛔` with owner note); zero `🔲`')
L.push('- [ ] Look via computed-style · Feel via real events · Behaviour via Playwright')
L.push('- [ ] Demo cache-buster bumped · [ ] Owner sign-off')
L.push('')

const outMd = L.join('\n')
if (doWrite) {
  const outPath = path.join(DS, 'strategy', 'coverage', `${id}.generated.md`)
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, outMd)
  console.error(`wrote ${rel(outPath)}  (review, then merge into ${id}.md)`)
} else {
  process.stdout.write(outMd)
}
